class LayoutBuilderWidget(forms.Widget):
    template_name = "netbox_device_view/widgets/layout_builder.html"

    class Media:
        css = {"all": ("netbox_device_view/css/device_view.css", "netbox_device_view/css/layout_builder.css")}
        js = ("netbox_device_view/js/layout_builder.js",)

    def get_context(self, name, value, attrs):
        if isinstance(value, str):
            try:
                value = json.loads(value)
            except json.JSONDecodeError:
                value = {}
        device_type_ids = list(self.attrs.get("device_type_ids", []))
        existing_grid_template_area = self.attrs.get("grid_template_area", "")
        self.attrs.pop("device_type_ids", None)
        self.attrs.pop("grid_template_area", None)
        context = super().get_context(name, value, attrs)
        source_device_type_id = (value or {}).get("source_device_type_id")
        if source_device_type_id:
            device_type_ids.append(source_device_type_id)
        default_device_type_id = source_device_type_id or (device_type_ids[0] if device_type_ids else "")
        selected_device_types = DeviceType.objects.filter(pk__in=set(device_type_ids)).select_related("manufacturer").order_by(
            "manufacturer__name", "model"
        )
        device_types = DeviceType.objects.select_related("manufacturer").order_by("manufacturer__name", "model")
        context["widget"]["value"] = json.dumps(value or {})
        context["device_type_options"] = [
            {
                "id": device_type.pk,
                "model": f"{device_type.manufacturer} {device_type.model}" if device_type.manufacturer else device_type.model,
            }
            for device_type in device_types
        ]
        context["device_type_layout_data"] = [
            get_device_type_layout_data(device_type) for device_type in selected_device_types
        ]
        context["layout_data_url_template"] = reverse(
            "plugins:netbox_device_view:devicetype_layout_data",
            kwargs={"pk": 0},
        ).replace("/0/", "/__device_type_id__/")
        context["default_device_type_id"] = default_device_type_id
        context["preview_url"] = reverse("plugins:netbox_device_view:deviceview_preview")
        context["devices_url_template"] = reverse(
            "plugins:netbox_device_view:devicetype_devices",
            kwargs={"pk": 0},
        ).replace("/0/", "/__device_type_id__/")
        context["parse_url"] = reverse("plugins:netbox_device_view:deviceview_parse_css")
        # The saved CSS is the source of truth: open whatever is stored, including
        # hand-written layouts with module or front/rear variants.
        context["initial_layout"] = parse_grid_css(existing_grid_template_area)
        return context


class DeviceViewForm(NetBoxModelForm):
    device_types = forms.ModelMultipleChoiceField(
        queryset=DeviceType.objects.all(),
        required=True,
        widget=APISelectMultiple(
            api_url="/api/dcim/device-types/",
        ),
        help_text="Select one or more device types that will use this view"
    )
    layout_config = forms.JSONField(
        required=False,
        widget=LayoutBuilderWidget,
        help_text="Use the visual builder to generate the device-view grid CSS.",
    )
    grid_template_area = forms.CharField(
        required=False,
        widget=forms.Textarea,
        help_text="Generated by the visual builder, or edited directly for advanced/custom layouts.",
    )

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        device_type_ids = []
        grid_template_area = ""
        if self.instance.pk:
            device_type_ids = list(self.instance.device_types.values_list("pk", flat=True))
            grid_template_area = self.instance.grid_template_area or ""
        elif self.data:
            device_type_ids = self.data.getlist("device_types")
            grid_template_area = self.data.get("grid_template_area", "")
        elif self.initial.get("device_types"):
            initial_types = self.initial["device_types"]
            device_type_ids = initial_types if isinstance(initial_types, (list, tuple)) else [initial_types]
        self.fields["layout_config"].widget.attrs["device_type_ids"] = device_type_ids
        self.fields["layout_config"].widget.attrs["grid_template_area"] = grid_template_area
    
    class Meta:
        model = DeviceView
        fields = ("name", "device_types", "layout_config", "grid_template_area", "tags")
    
    def clean_device_types(self):
        """Validate that selected device types aren't already assigned to other views"""
        device_types = self.cleaned_data['device_types']
        
        # Check if any of the selected device types are already assigned
        for dt in device_types:
            existing = DeviceView.objects.filter(device_types=dt)
            if self.instance.pk:
                # Exclude current instance when editing
                existing = existing.exclude(pk=self.instance.pk)
            
            if existing.exists():
                raise forms.ValidationError(
                    f"Device type '{dt.model}' is already assigned to another view: {existing.first()}"
                )
        
        return device_types

    def clean(self):
        super().clean()  # NetBoxModelForm.clean() returns None
        cleaned_data = self.cleaned_data
        layout_config = normalize_config(cleaned_data.get("layout_config"))
        submitted_css = (cleaned_data.get("grid_template_area") or "").strip()

        if layout_config is None:
            if not submitted_css:
                self.add_error("grid_template_area", "Enter CSS here or build a layout with the visual builder.")
            return cleaned_data

        try:
            generated_css = generate_grid_css(layout_config)
        except ValueError as exc:
            self.add_error("layout_config", str(exc))
            return cleaned_data

        if submitted_css and submitted_css != generated_css.strip():
            # The Advanced CSS was edited after the builder last synced it:
            # keep the hand edit and rebuild the builder config from it.
            problems = css_problems(submitted_css)
            if problems:
                self.add_error("grid_template_area", problems)
                return cleaned_data
            parsed = parse_grid_css(submitted_css)
            layout_config.update(layouts=parsed["layouts"], extra_css=parsed["extra_css"])
        else:
            cleaned_data["grid_template_area"] = generated_css

        cleaned_data["layout_config"] = layout_config
        return cleaned_data

    def save(self, commit=True):
        instance = super().save(commit=False)
        instance.grid_template_area = self.cleaned_data["grid_template_area"]
        instance.layout_config = self.cleaned_data.get("layout_config") or {}

        if commit:
            instance.save()
            self.save_m2m()

        return instance


